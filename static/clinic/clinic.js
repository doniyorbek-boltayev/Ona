function lineChart({ days, series, min, max, step, threshold, unit }) {
  const W = 520, H = 190, L = 34, R = 30, Tp = 10, B = 24;
  const x = (i) => L + (W - L - R) * (days.length > 1 ? i / (days.length - 1) : 0.5);
  const y = (v) => Tp + (H - Tp - B) * (1 - (v - min) / (max - min));
  let gap = step; while ((max - min) / gap > 6) gap *= 2;
  const ticks = []; for (let v = min; v <= max + 1e-9; v += gap) ticks.push(v);
  const svg = h("svg", { viewBox: `0 0 ${W} ${H}`, role: "img" });
  for (const v of ticks) {
    svg.append(h("line", { x1: L, x2: W - R, y1: y(v), y2: y(v), stroke: "#EDE8DF", "stroke-width": 1 }),
      h("text", { x: L - 6, y: y(v) + 4, "text-anchor": "end", "font-size": 11, fill: "#6B7A80" }, Math.round(v * 10) / 10));
  }
  days.forEach((d, i) => { if (i % 3 === (days.length - 1) % 3) svg.append(h("text", { x: x(i), y: H - 6, "text-anchor": "middle", "font-size": 11, fill: "#6B7A80" }, shortDay(d))); });
  for (const th of threshold || []) {
    svg.append(h("line", { x1: L, x2: W - R, y1: y(th.value), y2: y(th.value), stroke: "#d03b3b", "stroke-width": 1.2, "stroke-dasharray": "5 4" }),
      h("text", { x: W - R + 5, y: y(th.value) + 4, "font-size": 10.5, fill: "#6B7A80" }, th.label));
  }
  series.forEach((s) => {
    let d = "", pen = false;
    s.values.forEach((v, i) => { if (v == null) { pen = false; return; } d += (pen ? "L" : "M") + x(i).toFixed(1) + " " + y(v).toFixed(1); pen = true; });
    svg.append(h("path", { d, fill: "none", stroke: s.color, "stroke-width": 2, "stroke-linejoin": "round", "stroke-linecap": "round" }));
    s.values.forEach((v, i) => { if (v != null) svg.append(h("circle", { cx: x(i), cy: y(v), r: 4, fill: s.color, stroke: "#fff", "stroke-width": 2 })); });
  });
  // hover layer: crosshair + tooltip, hit area is the whole plot
  const cross = h("line", { y1: Tp, y2: H - B, stroke: "#9AA7AC", "stroke-width": 1, visibility: "hidden" });
  const tip = h("div", { style: "position:absolute;pointer-events:none;background:#1E2A2E;color:#fff;font-size:12px;padding:6px 9px;border-radius:8px;white-space:nowrap;display:none;z-index:2" });
  svg.append(cross, h("rect", { x: L, y: Tp, width: W - L - R, height: H - Tp - B, fill: "transparent",
    onmousemove: (e) => {
      const box = svg.getBoundingClientRect();
      const i = Math.max(0, Math.min(days.length - 1, Math.round(((e.clientX - box.left) / box.width * W - L) / (W - L - R) * (days.length - 1))));
      cross.setAttribute("x1", x(i)); cross.setAttribute("x2", x(i)); cross.setAttribute("visibility", "visible");
      tip.replaceChildren(h("b", {}, shortDay(days[i])), ...series.map((s) => h("div", {}, h("i", { style: `display:inline-block;width:8px;height:8px;border-radius:50%;background:${s.color};margin-right:6px` }), `${s.name}: ${s.values[i] ?? "—"}${s.values[i] != null && unit ? " " + unit : ""}`)));
      tip.style.display = "block";
      tip.style.left = Math.min(box.width - 150, Math.max(0, x(i) / W * box.width + 10)) + "px"; tip.style.top = "4px";
    },
    onmouseleave: () => { cross.setAttribute("visibility", "hidden"); tip.style.display = "none"; } }));
  return h("div", { class: "chart", style: "position:relative" }, svg, tip,
    series.length > 1 ? h("div", { class: "legend" }, series.map((s) => h("span", {}, h("i", { style: "background:" + s.color }), s.name)),
      threshold ? h("span", {}, h("i", { style: "background:#d03b3b" }), threshold[0].legend) : null) : null);
}

function chartCard(title, build, values) {
  return h("section", { class: "card" }, h("h3", {}, title), values.some((v) => v != null) ? build() : h("div", { class: "empty" }, t("noData")));
}

function padRange(values, step, floorMin, ceilMax) {
  const v = values.filter((x) => x != null);
  if (!v.length) return [0, 1];
  return [Math.min(floorMin ?? Infinity, Math.floor((Math.min(...v) - step / 2) / step) * step), Math.max(ceilMax ?? -Infinity, Math.ceil((Math.max(...v) + step / 2) / step) * step)];
}

